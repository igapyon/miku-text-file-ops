import { readFileSync, writeFileSync } from "node:fs";

const [inputPath, outputPath] = process.argv.slice(2);
if (inputPath === undefined || outputPath === undefined) {
  throw new Error(
    "Usage: node scripts/generate-simple-case-folding.mjs INPUT OUTPUT",
  );
}

const pairs = [];
for (const line of readFileSync(inputPath, "utf8").split(/\r?\n/u)) {
  const match = /^([0-9A-F]+);\s*([CS]);\s*([0-9A-F]+);/u.exec(line);
  if (match === null) {
    continue;
  }
  pairs.push([Number.parseInt(match[1], 16), Number.parseInt(match[3], 16)]);
}
pairs.sort((left, right) => left[0] - right[0]);

const values = pairs.flat().map((value) => `0x${value.toString(16)}`);
const rows = [];
for (let index = 0; index < values.length; index += 12) {
  rows.push(`  ${values.slice(index, index + 12).join(", ")},`);
}

const output = `// Generated by scripts/generate-simple-case-folding.mjs.
// Source: Unicode 17.0.0 CaseFolding.txt, status C and S mappings.
// License: https://www.unicode.org/license.txt

const SIMPLE_CASE_FOLDING_PAIRS = new Uint32Array([
${rows.join("\n")}
]);

const reverseMappings = new Map<number, number[]>();
for (let index = 0; index < SIMPLE_CASE_FOLDING_PAIRS.length; index += 2) {
  const source = SIMPLE_CASE_FOLDING_PAIRS[index] as number;
  const folded = SIMPLE_CASE_FOLDING_PAIRS[index + 1] as number;
  const values = reverseMappings.get(folded);
  if (values === undefined) {
    reverseMappings.set(folded, [source]);
  } else {
    values.push(source);
  }
}

export function simpleCaseFoldCodePoint(codePoint: number): number {
  let low = 0;
  let high = SIMPLE_CASE_FOLDING_PAIRS.length / 2 - 1;
  while (low <= high) {
    const middle = Math.floor((low + high) / 2);
    const source = SIMPLE_CASE_FOLDING_PAIRS[middle * 2] as number;
    if (source === codePoint) {
      return SIMPLE_CASE_FOLDING_PAIRS[middle * 2 + 1] as number;
    }
    if (source < codePoint) {
      low = middle + 1;
    } else {
      high = middle - 1;
    }
  }
  return codePoint;
}

export function simpleCaseFoldEquivalents(
  codePoint: number,
): readonly number[] {
  const folded = simpleCaseFoldCodePoint(codePoint);
  const equivalents = reverseMappings.get(folded);
  return equivalents === undefined ? [folded] : [folded, ...equivalents];
}

export function simpleCaseFold(text: string): string {
  return Array.from(text, (scalar) =>
    String.fromCodePoint(simpleCaseFoldCodePoint(scalar.codePointAt(0) as number)),
  ).join("");
}
`;

writeFileSync(outputPath, output, "utf8");
